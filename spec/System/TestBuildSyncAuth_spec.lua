-- cspell:ignore PlayerOne playerone DZLD Adevice Agrant Aietf Aoauth Aparams organisation
describe("BuildSyncAuth", function()
	local auth = require("Modules.BuildSyncAuth")

	it("builds form bodies for the device flow", function()
		assert.are.equals("client_id=Iv23liBVqYBGxpDZLDSv", auth.deviceCodeBody())
		assert.are.equals("client_id=Iv23liBVqYBGxpDZLDSv&device_code=abc%2F1&grant_type=urn%3Aietf%3Aparams%3Aoauth%3Agrant-type%3Adevice_code", auth.pollBody("abc/1"))
		assert.are.equals("client_id=Iv23liBVqYBGxpDZLDSv&grant_type=refresh_token&refresh_token=ghr_x", auth.refreshBody("ghr_x"))
	end)

	it("turns token responses into sessions", function()
		local s = auth.sessionFromToken({ access_token = "ghu_a", expires_in = 28800, refresh_token = "ghr_b", refresh_token_expires_in = 15897600 }, 1000, "PlayerOne")
		assert.are.equals("ghu_a", s.access)
		assert.are.equals("ghr_b", s.refresh)
		assert.are.equals(29800, s.accessExp)
		assert.are.equals(15898600, s.refreshExp)
		assert.are.equals("PlayerOne", s.login)
		local none, err = auth.sessionFromToken({ error = "bad_refresh_token" }, 1000)
		assert.is_nil(none)
		assert.are.equals("Your GitHub sign-in has run out. Sign in again.", err)
	end)

	it("decides when to refresh", function()
		local s = { access = "a", accessExp = 10000, refresh = "r", refreshExp = 50000 }
		assert.are.equals("ok", auth.tokenStatus(s, 9000))
		assert.are.equals("refresh", auth.tokenStatus(s, 9800))
		assert.are.equals("refresh", auth.tokenStatus(s, 20000))
		assert.are.equals("expired", auth.tokenStatus(s, 49990))
		assert.are.equals("ok", auth.tokenStatus({ access = "a" }, 99999)) -- non-expiring token
		assert.are.equals("expired", auth.tokenStatus({ access = "a", accessExp = 10 }, 100))
		assert.are.equals("expired", auth.tokenStatus(nil, 1))
	end)

	it("reads device flow poll replies", function()
		assert.are.equals("done", auth.pollOutcome({ access_token = "x" }))
		assert.are.equals("pending", auth.pollOutcome({ error = "authorization_pending" }))
		assert.are.equals("slow_down", auth.pollOutcome({ error = "slow_down", interval = 10 }))
		assert.are.equals("denied", auth.pollOutcome({ error = "access_denied" }))
		assert.are.equals("expired", auth.pollOutcome({ error = "expired_token" }))
		assert.are.equals("error", auth.pollOutcome({ error = "device_flow_disabled" }))
		assert.are.equals("error", auth.pollOutcome(nil))
	end)

	it("only auto-pushes the player's own builds", function()
		assert.is_true(auth.isOwnBuild("D:\\Builds\\PlayerOne\\3.29\\RF.xml", "D:/Builds/", "PlayerOne"))
		assert.is_true(auth.isOwnBuild("d:/builds/playerone/RF.xml", "D:\\Builds", "PlayerOne"))
		assert.is_false(auth.isOwnBuild("D:/Builds/Friend/RF.xml", "D:/Builds/", "PlayerOne"))
		assert.is_false(auth.isOwnBuild("D:/Builds/PlayerOneX/RF.xml", "D:/Builds/", "PlayerOne"))
		assert.is_false(auth.isOwnBuild("D:/Builds/RF.xml", "D:/Builds/", ""))
	end)

	it("explains missing repo access", function()
		assert.truthy(auth.repoAccessHint(404, "POE-Builds", "poe-builds"):find("add you to the POE%-Builds organisation"))
	end)
end)
